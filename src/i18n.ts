// 最小国际化：系统语言检测（zh→中文，其余→英文）+ 设置页可切换（系统/中文/英文）。
// 切换语言 = 写 localStorage + location.reload()，刷新后全量渲染即"不遗漏"。
// 字典以 zh 为源，en 用 Record<keyof typeof zh, string> 保证键完整，缺翻译编译报错。

export type Lang = 'zh' | 'en';
export type LangSetting = 'system' | Lang;

const KEY = 'sugt_lang';

export function langSetting(): LangSetting {
  const v = localStorage.getItem(KEY);
  return v === 'zh' || v === 'en' || v === 'system' ? v : 'system';
}

export function lang(): Lang {
  const s = langSetting();
  if (s !== 'system') return s;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function setLang(s: LangSetting): void {
  localStorage.setItem(KEY, s);
  location.reload();
}

// 支持 {name} 占位插值：t('delete.body', { name: 'x' })
export function t(key: TKey, vars?: Record<string, string | number>): string {
  const s = dict[lang()][key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : s;
}

